import os
import sys
import datetime
import joblib
import numpy as np
import pandas as pd
import streamlit as st
from fpdf import FPDF
from fpdf.enums import XPos, YPos

sys.path.append(os.path.join(os.path.dirname(__file__), ".."))

MODEL_PATH = os.path.join(os.path.dirname(__file__), "..", "models", "loan_model.pkl")
SCALER_PATH = os.path.join(os.path.dirname(__file__), "..", "models", "scaler.pkl")


# ---------- Friendly labels ----------
FEATURE_LABELS = {
    "no_of_dependents": "Number of Dependents",
    "education": "Education Level",
    "self_employed": "Self Employed",
    "income_annum": "Annual Income",
    "loan_amount": "Loan Amount",
    "loan_term": "Loan Term",
    "cibil_score": "CIBIL Credit Score",
    "residential_assets_value": "Residential Assets",
    "commercial_assets_value": "Commercial Assets",
    "luxury_assets_value": "Luxury Assets",
    "bank_asset_value": "Bank Assets",
    "total_assets": "Total Assets",
    "loan_income_ratio": "Loan-to-Income Ratio",
    "loan_asset_ratio": "Loan-to-Asset Ratio",
    "monthly_payment": "Estimated Monthly Payment",
    "disposable_income": "Disposable Income",
}


@st.cache_resource
def load_artifacts():
    model = joblib.load(MODEL_PATH)
    scaler = joblib.load(SCALER_PATH)
    return model, scaler


def build_input_row(no_of_dependents, education, self_employed,
                    income_annum, loan_amount, loan_term, cibil_score,
                    residential_assets, commercial_assets,
                    luxury_assets, bank_assets):
    total_assets = residential_assets + commercial_assets + luxury_assets + bank_assets
    loan_income_ratio = loan_amount / (income_annum + 1)
    loan_asset_ratio = loan_amount / (total_assets + 1)
    monthly_payment = loan_amount / loan_term
    disposable_income = income_annum - monthly_payment

    row = {
        "no_of_dependents": no_of_dependents,
        "education": 1 if education == "Graduate" else 0,
        "self_employed": 1 if self_employed == "Yes" else 0,
        "income_annum": np.log1p(income_annum),
        "loan_amount": np.log1p(loan_amount),
        "loan_term": loan_term,
        "cibil_score": cibil_score,
        "residential_assets_value": residential_assets,
        "commercial_assets_value": commercial_assets,
        "luxury_assets_value": luxury_assets,
        "bank_asset_value": bank_assets,
        "total_assets": np.log1p(total_assets),
        "loan_income_ratio": loan_income_ratio,
        "loan_asset_ratio": loan_asset_ratio,
        "monthly_payment": monthly_payment,
        "disposable_income": disposable_income,
    }
    return pd.DataFrame([row])


def explain_prediction(model, input_scaled_df, top_n=5):
    if not hasattr(model, "feature_importances_"):
        return []
    importances = model.feature_importances_
    values = input_scaled_df.values[0]
    contributions = importances * values

    cols = input_scaled_df.columns
    contrib_df = pd.DataFrame({
        "feature": cols,
        "importance": importances,
        "scaled_value": values,
        "contribution": contributions,
    })
    contrib_df["abs_contribution"] = contrib_df["contribution"].abs()
    contrib_df = contrib_df.sort_values("abs_contribution", ascending=False).head(top_n)

    explanations = []
    for _, row in contrib_df.iterrows():
        friendly = FEATURE_LABELS.get(row["feature"], row["feature"])
        direction = "supports APPROVAL" if row["contribution"] > 0 else "supports REJECTION"
        explanations.append(
            f"{friendly}: importance={row['importance']:.3f}, "
            f"scaled value={row['scaled_value']:.2f} -> {direction}"
        )
    return explanations


# ---------- PDF Report Generation ----------
class PDFReport(FPDF):
    def header(self):
        self.set_font("Helvetica", "B", 16)
        self.set_text_color(30, 60, 120)
        self.cell(0, 10, "Motz Financial Services",
                  new_x=XPos.LMARGIN, new_y=YPos.NEXT, align="C")
        self.set_font("Helvetica", "", 11)
        self.set_text_color(0, 0, 0)
        self.cell(0, 6, "Loan Approval Assessment Report",
                  new_x=XPos.LMARGIN, new_y=YPos.NEXT, align="C")
        self.ln(3)
        self.set_draw_color(30, 60, 120)
        self.set_line_width(0.6)
        self.line(10, self.get_y(), 200, self.get_y())
        self.ln(5)

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(120, 120, 120)
        self.cell(0, 10, f"Page {self.page_no()} | Generated by Motz AI System", align="C")


def safe_text(s):
    return (str(s)
            .replace("→", "->")
            .replace("✅", "[APPROVED]")
            .replace("❌", "[REJECTED]")
            .replace("•", "-")
            .replace("–", "-")
            .replace("’", "'")
            .replace("“", '"')
            .replace("”", '"'))


def generate_pdf(applicant: dict, prediction: int, proba: list,
                 explanations: list) -> bytes:
    pdf = PDFReport()
    pdf.add_page()
    pdf.set_auto_page_break(auto=True, margin=15)

    # --- 1. Applicant Summary ---
    pdf.set_font("Helvetica", "B", 12)
    pdf.cell(0, 8, "1. Applicant Summary",
             new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.set_font("Helvetica", "", 10)

    for k, v in applicant.items():
        pdf.set_x(10)  # reset X to left margin
        pdf.cell(80, 6, safe_text(k))
        pdf.cell(0, 6, safe_text(v),
                 new_x=XPos.LMARGIN, new_y=YPos.NEXT)

    pdf.ln(4)

    # --- 2. Prediction Result ---
    pdf.set_font("Helvetica", "B", 12)
    pdf.cell(0, 8, "2. Prediction Result",
             new_x=XPos.LMARGIN, new_y=YPos.NEXT)

    status = "APPROVED" if prediction == 1 else "REJECTED"

    pdf.set_x(10)
    pdf.set_font("Helvetica", "", 10)
    pdf.cell(80, 6, "Decision:")

    if prediction == 1:
        pdf.set_text_color(0, 140, 0)
    else:
        pdf.set_text_color(200, 0, 0)
    pdf.set_font("Helvetica", "B", 11)
    pdf.cell(0, 6, status, new_x=XPos.LMARGIN, new_y=YPos.NEXT)

    pdf.set_text_color(0, 0, 0)
    pdf.set_font("Helvetica", "", 10)
    pdf.set_x(10)
    pdf.cell(80, 6, "Approval Probability:")
    pdf.cell(0, 6, f"{proba[1]*100:.2f}%",
             new_x=XPos.LMARGIN, new_y=YPos.NEXT)

    pdf.set_x(10)
    pdf.cell(80, 6, "Rejection Probability:")
    pdf.cell(0, 6, f"{proba[0]*100:.2f}%",
             new_x=XPos.LMARGIN, new_y=YPos.NEXT)

    pdf.ln(4)

    # --- 3. Key Factors ---
    pdf.set_font("Helvetica", "B", 12)
    pdf.cell(0, 8, "3. Key Factors Influencing Decision",
             new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.set_font("Helvetica", "", 10)

    if explanations:
        for i, line in enumerate(explanations, 1):
            pdf.set_x(10)  # CRITICAL: reset X before multi_cell
            pdf.multi_cell(0, 6, safe_text(f"{i}. {line}"))
    else:
        pdf.set_x(10)
        pdf.multi_cell(0, 6, "Explanation not available for this model type.")

    pdf.ln(4)

    # --- 4. Recommendation ---
    pdf.set_font("Helvetica", "B", 12)
    pdf.cell(0, 8, "4. Recommendation",
             new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.set_font("Helvetica", "", 10)

    if prediction == 1:
        rec = ("The applicant meets the key criteria for loan approval. "
               "The system recommends APPROVAL, subject to final officer review.")
    else:
        rec = ("The applicant does not meet the key criteria for loan approval. "
               "Consider advising the applicant to improve their CIBIL score "
               "or reduce the requested loan amount.")

    pdf.set_x(10)
    pdf.multi_cell(0, 6, safe_text(rec))

    pdf.ln(6)
    pdf.set_font("Helvetica", "I", 8)
    pdf.set_text_color(100, 100, 100)
    pdf.set_x(10)
    pdf.cell(0, 5,
             safe_text(f"Generated on: {datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')}"),
             new_x=XPos.LMARGIN, new_y=YPos.NEXT)

    return bytes(pdf.output())


# ---------- Main App ----------
def main():
    st.set_page_config(page_title="Loan Approval Predictor", page_icon="🏦", layout="wide")
    st.title("🏦 Motz Financial Services – Loan Approval Predictor")
    st.markdown("Predict whether a loan application will be **Approved ✅** or **Rejected ❌**.")

    try:
        model, scaler = load_artifacts()
    except Exception as e:
        st.error(f"⚠️ Model not found. Please run `python -m src.model_training` first.\n\n{e}")
        return

    st.sidebar.header("📋 Applicant Information")

    with st.sidebar:
        no_of_dependents = st.number_input("Number of Dependents", 0, 10, 2)
        education = st.selectbox("Education", ["Graduate", "Not Graduate"])
        self_employed = st.selectbox("Self Employed", ["Yes", "No"])
        income_annum = st.number_input("Annual Income (R)", min_value=0, value=5000000, step=100000)
        loan_amount = st.number_input("Loan Amount (R)", min_value=0, value=15000000, step=100000)
        loan_term = st.number_input("Loan Term (years)", min_value=1, value=10, step=1)
        cibil_score = st.slider("CIBIL Score", 300, 900, 700)

        st.markdown("---")
        st.subheader("Asset Values")
        residential = st.number_input("Residential Assets (R)", 0, value=5000000, step=100000)
        commercial = st.number_input("Commercial Assets (R)", 0, value=2000000, step=100000)
        luxury = st.number_input("Luxury Assets (R)", 0, value=10000000, step=100000)
        bank = st.number_input("Bank Assets (R)", 0, value=3000000, step=100000)

        predict_btn = st.button("🔮 Predict Loan Status", width="stretch")

    # Applicant summary — ALL VALUES AS STRINGS to prevent Arrow error
    applicant_summary = {
        "Number of Dependents": str(no_of_dependents),
        "Education": education,
        "Self Employed": self_employed,
        "Annual Income (R)": f"{income_annum:,}",
        "Loan Amount (R)": f"{loan_amount:,}",
        "Loan Term (years)": str(loan_term),
        "CIBIL Score": str(cibil_score),
        "Residential Assets (R)": f"{residential:,}",
        "Commercial Assets (R)": f"{commercial:,}",
        "Luxury Assets (R)": f"{luxury:,}",
        "Bank Assets (R)": f"{bank:,}",
    }

    col1, col2 = st.columns([2, 1])

    with col1:
        st.subheader("📊 Application Summary")
        summary_df = pd.DataFrame({
            "Field": list(applicant_summary.keys()),
            "Value": [str(v) for v in applicant_summary.values()],  # Force strings
        })
        st.dataframe(summary_df, width="stretch", hide_index=True)

        st.markdown("#### 📄 Generate Report")
        if predict_btn:
            st.info("Prediction generated — scroll right to see the result and download the report.")
        else:
            st.caption("Click **Predict Loan Status** first, then come back to download a detailed report.")

    with col2:
        st.subheader("🎯 Prediction")
        if predict_btn:
            input_df = build_input_row(
                no_of_dependents, education, self_employed,
                income_annum, loan_amount, loan_term, cibil_score,
                residential, commercial, luxury, bank
            )
            expected_cols = list(scaler.feature_names_in_)
            input_df = input_df[expected_cols]
            input_scaled = scaler.transform(input_df)
            input_scaled_df = pd.DataFrame(input_scaled, columns=expected_cols)

            pred = model.predict(input_scaled)[0]
            proba = model.predict_proba(input_scaled)[0]

            if pred == 1:
                st.success(f"✅ **LOAN APPROVED**\n\nConfidence: **{proba[1]*100:.2f}%**")
                st.balloons()
            else:
                st.error(f"❌ **LOAN REJECTED**\n\nConfidence: **{proba[0]*100:.2f}%**")

            st.markdown("#### Probability Breakdown")
            st.progress(float(proba[1]), text=f"Approval: {proba[1]*100:.2f}%")
            st.progress(float(proba[0]), text=f"Rejection: {proba[0]*100:.2f}%")

            st.session_state["pred"] = int(pred)
            st.session_state["proba"] = proba.tolist()
            st.session_state["explanations"] = explain_prediction(model, input_scaled_df)
            st.session_state["applicant"] = applicant_summary
        else:
            st.info("👈 Fill in applicant details and click **Predict**.")

    # ---- Explanation Panel ----
    if predict_btn:
        st.markdown("---")
        st.subheader("🔍 Why this decision?")
        explanations = st.session_state.get("explanations", [])
        if explanations:
            st.markdown("**Top factors influencing this decision:**")
            for i, exp in enumerate(explanations, 1):
                st.markdown(f"{i}. {exp}")
        else:
            st.caption("Explanation not available for this model.")

        st.markdown("### 📥 Download Report")
        try:
            pdf_bytes = generate_pdf(
                applicant=st.session_state["applicant"],
                prediction=st.session_state["pred"],
                proba=st.session_state["proba"],
                explanations=st.session_state.get("explanations", []),
            )
            st.download_button(
                label="📄 Download PDF Report",
                data=pdf_bytes,
                file_name=f"loan_report_{datetime.datetime.now().strftime('%Y%m%d_%H%M%S')}.pdf",
                mime="application/pdf",
                width="stretch",
            )
        except Exception as e:
            st.error(f"Could not generate PDF: {e}")

    st.markdown("---")
    st.caption("© 2026 Motz Financial Services")


if __name__ == "__main__":
    main()